"""產生 licenses/THIRD-PARTY-NOTICES.txt：列出隨程式散布的 Rust crate 及其授權條文。

只納入 x86_64-pc-windows-msvc 一般相依（不含 build／dev 相依與 proc-macro）。
相同的授權條文只輸出一次，並列出使用該條文的 crate。
用法：python -I scripts/gen-notices.py（在專案根目錄執行）
"""
import hashlib
import json
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'licenses', 'THIRD-PARTY-NOTICES.txt')
TARGET = 'x86_64-pc-windows-msvc'
# 允許的授權（SPDX 運算式中至少要有一個選項在此清單內）
PERMISSIVE = {'MIT', 'Apache-2.0', 'BSD-2-Clause', 'BSD-3-Clause', 'ISC', 'Zlib', '0BSD', 'Unlicense',
              'BSL-1.0', 'CC0-1.0', 'Unicode-3.0', 'Unicode-DFS-2016', 'LicenseRef-Slint-Royalty-free-2.0'}


def run(*args):
    return subprocess.run(args, cwd=ROOT, capture_output=True, text=True, encoding='utf-8', check=True).stdout


def shipped_packages():
    out = run('cargo', 'tree', '-e', 'normal', '--target', TARGET, '--prefix', 'none', '-f', '{p}')
    pkgs = set()
    for line in out.splitlines():
        if '(proc-macro)' in line or not line.strip():
            continue
        m = re.match(r'(\S+) v(\S+)', line.strip())
        if m and m.group(1) != 'pdfword':
            pkgs.add((m.group(1), m.group(2)))
    return pkgs


def license_ok(expr):
    """每個 AND 子句都至少要有一個允許的選項"""
    if not expr:
        return False
    expr = expr.replace('/', ' OR ').replace('(', ' ').replace(')', ' ')
    for clause in re.split(r'\s+AND\s+', expr):
        opts = [o.strip() for o in re.split(r'\s+OR\s+', clause) if o.strip()]
        opts = [re.sub(r'\s+WITH\s+.*', '', o) for o in opts]
        if not any(o in PERMISSIVE for o in opts):
            return False
    return True


def license_texts(pkg_dir):
    """套件根目錄的 LICENSE*／COPYING*／NOTICE* 檔，以及 LICENSES/ 子資料夾內的檔案"""
    paths = []
    for f in sorted(os.listdir(pkg_dir)):
        full = os.path.join(pkg_dir, f)
        if os.path.isfile(full) and f.upper().startswith(('LICENSE', 'LICENCE', 'COPYING', 'NOTICE', 'UNLICENSE')):
            paths.append(full)
        elif os.path.isdir(full) and f.upper() in ('LICENSES', 'LICENSE'):
            for g in sorted(os.listdir(full)):
                # Slint 的 LICENSES 內含 GPL 與商業授權，只取本專案採用的 Royalty-free 條文
                if 'slint' in os.path.basename(pkg_dir).lower() and 'ROYALTY-FREE' not in g.upper():
                    continue
                paths.append(os.path.join(full, g))
    texts = []
    for n in paths:
        with open(n, encoding='utf-8', errors='replace') as fh:
            texts.append(fh.read().strip())
    return texts


