def apache_text(meta):
    """取 rayon 附的 Apache-2.0 全文"""
    for p in meta['packages']:
        if p['name'] == 'rayon':
            path = os.path.join(os.path.dirname(p['manifest_path']), 'LICENSE-APACHE')
            with open(path, encoding='utf-8') as fh:
                return fh.read().strip()
    raise RuntimeError('找不到 Apache-2.0 條文')


def main():
    meta = json.loads(run('cargo', 'metadata', '--format-version', '1', '--filter-platform', TARGET))
    by_id = {(p['name'], p['version']): p for p in meta['packages']}
    shipped = sorted(shipped_packages())

    bad = []
    groups = {}       # 條文雜湊 → (條文, [crate])
    no_text = []
    for name, ver in shipped:
        p = by_id.get((name, ver))
        if not p:
            continue
        lic = p.get('license') or ''
        if name.startswith(('slint', 'i-slint')):
            lic_used = 'LicenseRef-Slint-Royalty-free-2.0'
        else:
            lic_used = lic
        if not license_ok(lic_used):
            bad.append(f'{name} {ver}: {lic}')
        texts = license_texts(os.path.dirname(p['manifest_path']))
        label = f'{name} {ver}（{lic_used}）'
        if not texts:
            authors = '、'.join(p.get('authors') or []) or '見套件原始碼'
            no_text.append(f'{label} — 著作權人：{authors}')
            continue
        for t in texts:
            h = hashlib.sha256(t.encode()).hexdigest()
            groups.setdefault(h, (t, []))[1].append(label)

    if bad:
        print('發現非寬鬆授權的相依套件：', *bad, sep='\n  ')
        sys.exit(1)

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w', encoding='utf-8', newline='\r\n') as f:
        f.write('PDF 轉 Word — 第三方元件授權聲明\n')
        f.write('=' * 60 + '\n\n')
        f.write('本程式使用 Slint 1.18.1，依 Slint Royalty-free License 2.0 授權使用（於「說明 → 關於」顯示 AboutSlint）。\n')
        f.write('PDFium（pdfium.dll）及其內含元件的授權條文位於 licenses\\pdfium 資料夾。\n\n')
        f.write(f'以下列出隨程式散布的 {len(shipped)} 個 Rust crate。相同的授權條文只列一次。\n\n')
        if no_text:
            f.write('-' * 60 + '\n套件未附授權檔，授權依其 SPDX 宣告：\n')
            for l in no_text:
                f.write(f'  {l}\n')
            f.write('\n')
        for t, crates in sorted(groups.values(), key=lambda g: -len(g[1])):
            f.write('-' * 60 + '\n適用於：\n')
            for c in sorted(set(crates)):
                f.write(f'  {c}\n')
            f.write('\n' + t + '\n\n')
        f.write('=' * 60 + '\n標準授權條文（供上方「未附授權檔」的套件適用）\n' + '=' * 60 + '\n\n')
        f.write(MIT_TEXT + '\n\n' + '-' * 60 + '\n' + BSL_TEXT + '\n\n' + '-' * 60 + '\n')
        f.write(apache_text(meta) + '\n')
    print(f'已寫入 {OUT}：{len(shipped)} 個 crate、{len(groups)} 種條文、{len(no_text)} 個未附授權檔')


if __name__ == '__main__':
    main()
